// Helper to create Firebase-like Timestamp mock
const makeTimestamp = (daysAgo: number) => {
  const date = new Date();
  date.setDate(date.getDate() - daysAgo);
  return {
    toDate: () => date,
    seconds: Math.floor(date.getTime() / 1000),
    nanoseconds: 0,
    toLocaleDateString: () => date.toLocaleDateString()
  };
};

